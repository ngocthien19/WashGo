import { afterEach, expect, it, vi } from 'vitest'
import { createOrderRealtimeStore } from './orderRealtime'
afterEach(() => vi.useRealTimers())
const id = '11111111-1111-4111-8111-111111111111'
const event = (n, revision = 5) => ({ eventId: `22222222-2222-4222-8222-${String(n).padStart(12, '0')}`, orderId: id, revision, changeType: 'StatusChanged', occurredAt: '2026-11-26T01:00:00Z' })
it('coalesces bursts, ignores repeats and older revisions, accepts new events at the same revision', () => {
  vi.useFakeTimers()
  const store = createOrderRealtimeStore(), listener = vi.fn()
  store.subscribe(listener)
  store.changed(event(1)); store.changed(event(1)); store.changed(event(2))
  vi.advanceTimersByTime(200)
  expect(listener).toHaveBeenCalledTimes(1)
  expect(store.snapshot(id)).toBe('0:1')
  store.changed(event(3, 4)); store.changed({ ...event(4), orderId: '../other' })
  vi.advanceTimersByTime(200)
  expect(listener).toHaveBeenCalledTimes(1)
  store.changed(event(5))
  vi.advanceTimersByTime(200)
  expect(store.snapshot(id)).toBe('0:2')
  expect(store.snapshot('unrelated')).toBe('0:0')
  expect(store.snapshot()).toBe('0:2')
  store.dispose()
})
it('scope changes and reconnect invalidate every view; cleanup cancels queued work and can restart', () => {
  vi.useFakeTimers()
  const store = createOrderRealtimeStore(), listener = vi.fn()
  store.subscribe(listener)
  store.scopeChanged(event(1)); store.revalidate()
  vi.advanceTimersByTime(200)
  expect(store.snapshot(id)).toBe('1:0')
  expect(store.snapshot('another')).toBe('1:0')
  const signal = store.eventSnapshot(id)
  store.revalidate(); vi.advanceTimersByTime(200)
  expect(store.eventSnapshot(id)).toBe(signal)
  store.changed(event(2)); store.dispose(); vi.runAllTimers()
  expect(listener).toHaveBeenCalledTimes(2)
  const next = vi.fn(); store.subscribe(next); store.revalidate(); vi.advanceTimersByTime(200)
  expect(next).toHaveBeenCalledTimes(1)
  store.dispose()
})
