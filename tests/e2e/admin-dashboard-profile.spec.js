  await page.goto('/admin/profile')
  await expect(page.getByRole('heading', { name: 'Personal profile', exact: true })).toBeVisible({ timeout: 20000 })
  await expect(page.getByText('AdminProfile · Update 3', { exact: true })).toBeVisible()
  await expect(page.getByText('AdminProfile · Update 5', { exact: true })).toBeVisible()
  await expect(page.getByText('AdminProfile · Update 6', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'View all', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Refresh', exact: true })).toHaveCount(1)
  await expect(page.getByRole('button', { name: 'Edit information', exact: true })).toHaveClass(/bg-primary/)
  const sessions = page.getByRole('heading', { name: 'Signed-in sessions', exact: true }).locator('..')
  await expect(sessions.locator('dt').filter({ hasText: /^Signed in$/ }).first()).toHaveCSS('font-weight', '700')
