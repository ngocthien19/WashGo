test('Admin profile stale data and unknown writes block duplicate saves', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/admin/profile')
  await page.getByRole('button', { name: 'Edit information', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('textbox', { name: 'Full name', exact: true }).fill('Draft name')
  state.profile.version = '63935071200123458'
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('profile has changed')
  expect(state.saves).toBe(0)
  await dialog.getByRole('button', { name: 'Close', exact: true }).last().click()
  await page.getByRole('button', { name: 'Edit information', exact: true }).click()
  dialog = page.getByRole('dialog')
  state.unknownSave = true
  await dialog.getByRole('textbox', { name: 'Full name', exact: true }).fill('Another draft')
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('result is unknown')
  await expect(dialog.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled()
  expect(state.saves).toBe(1)
})

test('password change validates confirmation, handles a wrong current password and retains this session', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/admin/profile')
  await page.getByRole('button', { name: 'Change password', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Current password', { exact: true }).fill('OldPassword123')
  await dialog.getByLabel('New password', { exact: true }).fill('NewPassword123')
  await dialog.getByLabel('Confirm new password', { exact: true }).fill('mismatch')
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('does not match')
  expect(state.passwords).toBe(0)
  await dialog.getByLabel('Confirm new password', { exact: true }).fill('NewPassword123')
  state.wrongPassword = true
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  state.wrongPassword = false
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(state.sessions.map(row => row.isCurrent)).toEqual([true])
  expect(state.passwords).toBe(2)
  expect(await page.evaluate(() => localStorage.getItem('persist:root'))).not.toContain('NewPassword123')
})

