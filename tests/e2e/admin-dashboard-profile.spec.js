import { test, expect } from '@playwright/test'
import { setupAdmin as setup } from './helpers/adminSession'

test('admin dashboard uses real scoped aggregates and a distinct shared workspace', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'System overview', exact: true })).toBeVisible({ timeout: 20000 })
  await expect(page.getByText('WG-ADMIN-02', { exact: true })).toBeVisible()
  await expect(page.getByText('WG-WAIT-01', { exact: true })).toBeVisible()
  await expect(page.getByText('Waiting 17 hours 31 minutes', { exact: true })).toBeVisible()
  await expect(page.getByText(/Revenue uses payment\/refund dates/)).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Active merchants', exact: true }).locator('..')).toContainText('12')
  await expect(page.getByRole('heading', { name: 'Total customers', exact: true }).locator('..')).toContainText('—')
  await expect(page.getByRole('img', { name: 'Revenue chart', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Merchant management', exact: true })).toHaveAttribute('href', '/admin/merchants')
  await page.getByRole('button', { name: 'Collapse navigation', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Expand navigation', exact: true })).toBeVisible()
  expect(state.calls.some((call) => call.path === '/merchant/dashboard')).toBe(false)
  const finance = state.calls.find((call) => call.path === '/finance/revenue-report').body
  expect(finance).not.toHaveProperty('merchantId')
  expect(state.calls.find((call) => call.path === '/wash-order/summary').body).toEqual(finance)
})
test('custom dates anchor below the control and persist after reload', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/admin')
  await page.getByRole('button', { name: 'Custom', exact: true }).click()
  const popup = page.getByRole('dialog')
  await popup.getByLabel('From date', { exact: true }).fill('2026-11-01')
  await popup.getByLabel('To date', { exact: true }).fill('2026-11-07')
  await popup.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(page).toHaveURL(/period=custom/)
  await expect.poll(() => state.calls.filter((call) => call.path === '/finance/revenue-report').at(-1)?.body).toEqual({ fromDate: 1793466000, toDate: 1794070799 })
  await page.reload()
  await expect(page.getByRole('heading', { name: 'System overview', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Custom', exact: true })).toHaveAttribute('aria-pressed', 'true')
})
test('finance failure can retry without hiding other dashboard data', async ({ page }) => {
  const state = await setup(page)
  state.revenueError = true
  await page.goto('/admin')
  await expect(page.getByText('WG-ADMIN-02', { exact: true })).toBeVisible({ timeout: 20000 })
  await expect(page.getByRole('alert').first()).toBeVisible()
  state.revenueError = false
  await page.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(page.getByText('Ben Thanh Laundry', { exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
test('mobile dark profile uses auth data and keeps unsupported writes unavailable', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  const state = await setup(page, { dark: true })
  await page.goto('/admin/profile')
  await expect(page.getByRole('heading', { name: 'Personal profile', exact: true })).toBeVisible({ timeout: 20000 })
  await expect(page.getByRole('button', { name: 'Edit information', exact: true })).toBeDisabled()
  await expect(page.getByText('0901234567', { exact: true })).toBeVisible()
  await expect(page.getByText('Department', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Display language', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('link', { name: 'Dashboard', exact: true }).click()
  await expect(page).toHaveURL('/admin')
  await page.getByRole('button', { name: 'Open account menu', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Personal profile', exact: true }).click()
  await expect(page).toHaveURL('/admin/profile')
  expect(state.calls.some((call) => call.path === '/customer/me' || call.path === '/merchant-profile')).toBe(false)
})
test('profile signs out the current session', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/admin/profile')
  await page.getByRole('main').getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect(state.logout).toBe(1)
})
test('guests cannot query Admin data', async ({ page }) => {
  const state = await setup(page, { guest: true })
  await page.goto('/admin')
  await expect(page).toHaveURL(/\/login$/)
  expect(state.calls).toHaveLength(0)
})
