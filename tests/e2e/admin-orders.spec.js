test('order photos, distinct drop-off and pickup panels, and payment badges use real sources consistently', async ({ page }) => {
  const state = await setupAdminOrders(page, { merchant: true })
  state.orders[0].customerAvatarUrl = '/mock/customer.png'
  state.orders[0].items[0].serviceId = serviceId
  await page.goto('/admin/orders')
  const row = page.getByRole('row').filter({ hasText: 'WG-ADMIN-01' })
  await expect(row.getByRole('img', { name: 'Test Customer', exact: true })).toHaveAttribute('src', /customer.png$/)
  await expect(row.getByRole('img', { name: 'Test Laundry', exact: true })).toHaveAttribute('src', /merchant.png$/)
  await expect(row.getByRole('img', { name: 'Test Locker', exact: true })).toHaveAttribute('src', /locker.png$/)
  await expect(row.getByText('02812345678', { exact: true })).toBeVisible()
  const lockerHeader = page.getByRole('columnheader', { name: 'Locker', exact: true })
  expect((await lockerHeader.boundingBox()).width).toBeGreaterThanOrEqual(340)
  const badge = row.getByText('Unpaid', { exact: true })
  expect(await badge.evaluate(el => getComputedStyle(el).whiteSpace)).toBe('nowrap')
  const badgeColor = await badge.evaluate(el => getComputedStyle(el).backgroundColor)
  await row.getByRole('link', { name: 'WG-ADMIN-01', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'WG-ADMIN-01', exact: true })).toBeVisible()
  await expect(page.getByText('02812345678', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Order actions', exact: true })).toHaveCount(0)
  await expect(page.locator('main header').getByRole('button', { name: 'Assign collection', exact: true })).toBeVisible()
  const people = await page.getByRole('heading', { name: 'Customer & delivery partners', exact: true }).boundingBox()
  const services = await page.getByRole('heading', { name: 'Service information', exact: true }).boundingBox()
  expect(services.x).toBeGreaterThan(people.x)
  expect(await page.getByText('Deposited', { exact: true }).evaluate(el => getComputedStyle(el).fontWeight)).toBe('400')
  await expect(page.getByRole('img', { name: 'Test Customer', exact: true })).toHaveAttribute('src', /customer.png$/)
  await expect(page.getByRole('img', { name: 'Test Laundry', exact: true })).toHaveAttribute('src', /merchant.png$/)
  await expect(page.getByRole('img', { name: 'Wash', exact: true })).toHaveAttribute('src', /service.png$/)
  await expect(page.getByRole('heading', { name: 'Drop-off', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Pickup', exact: true })).toBeVisible()
  expect(await page.getByText('Unpaid', { exact: true }).evaluate(el => getComputedStyle(el).backgroundColor)).toBe(badgeColor)
})
