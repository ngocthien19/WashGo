test('Admin filters, summary and paging use server data and preserve URL', async ({ page }) => {
  const state = await setupAdminOrders(page, { merchant: true })
  await page.goto('/admin/orders?page=2')
  await expect(page.getByRole('table')).toContainText('WG-ADMIN-13')
  await page.reload()
  await expect(page.getByRole('table')).toContainText('WG-ADMIN-13')
  await page.getByRole('combobox', { name: 'Merchant', exact: true }).click()
  await page.getByRole('option', { name: 'Test Laundry', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`merchantId=${merchantId}`))
  await expect(page.getByRole('table')).toContainText('WG-ADMIN-01')
  await page.getByRole('combobox', { name: 'Order status', exact: true }).click()
  await page.getByRole('option', { name: 'Washing', exact: true }).click()
  await expect(page.getByText('No matching orders.', { exact: true })).toBeVisible()
  expect(state.calls.filter(call => call.path === '/wash-order/summary').at(-1).body).not.toHaveProperty('status')
  expect(state.calls.filter(call => call.path === '/wash-order/summary').at(-1).body).toMatchObject({ merchantId })
})
