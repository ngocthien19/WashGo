test('unknown assignment blocks duplicate writes and stale data never writes', async ({ page }) => {
  const state = await setupAdminOrders(page)
  state.unknown = true
  await page.goto(`/admin/orders/${orderId}`)
  await page.getByRole('button', { name: 'Assign merchant', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('radio', { name: 'Test Laundry', exact: true }).check()
  await dialog.getByRole('button', { name: 'Confirm assignment', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('outcome is unknown')
  await expect(dialog.getByRole('button', { name: 'Confirm assignment', exact: true })).toBeDisabled()
  expect(state.writes).toHaveLength(1)
  await dialog.getByText('Close', { exact: true }).click()
  state.unknown = false
  await page.getByRole('button', { name: 'Assign merchant', exact: true }).click()
  await page.getByRole('radio', { name: 'Test Laundry', exact: true }).check()
  state.stale = true
  await page.getByRole('button', { name: 'Confirm assignment', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('has changed')
  expect(state.writes).toHaveLength(1)
})
