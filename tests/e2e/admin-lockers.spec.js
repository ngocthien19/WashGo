import { expect, test } from '@playwright/test'
import { setupAdminLockers as setup, lockerId, merchantId } from './helpers/adminLockerSession'

const menu = async (page, action) => {
  await page.getByRole('button', { name: 'Actions for Central Locker', exact: true }).click()
  await page.getByRole('menuitem', { name: action, exact: true }).click()
}
const save = dialog => dialog.getByRole('button', { name: 'Save locker', exact: true }).click()

