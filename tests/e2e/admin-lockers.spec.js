test('delete blocks occupied stations and removes an unused station after confirmation', async ({ page }) => {
  const state = await setup(page)
  await page.goto('/admin/lockers')
  await menu(page, 'Delete locker')
  let dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('img', { name: 'Central Locker', exact: true })).toBeVisible()
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('goods or reservations')
  expect(state.writes).toHaveLength(0)
  await dialog.getByRole('button', { name: 'Close', exact: true }).last().click()
  state.lockers[0].boxes.forEach(box => {
    box.status = 1
  })
  await menu(page, 'Delete locker')
  dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox').check()
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('table')).not.toContainText('Central Locker')
  expect(state.writes[0]).toMatchObject({ method: 'DELETE', path: `/locker/${lockerId}` })
})

