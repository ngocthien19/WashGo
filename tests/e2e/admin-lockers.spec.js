test('mobile dark layout scrolls the table internally with opaque matching sticky action headers', async ({ page }) => {
  const state = await setup(page, { dark: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/admin/lockers')
  const table = page.getByRole('table')
  await expect(table).toContainText('Central Locker')
  const colors = await table.locator('th').evaluateAll(headers => headers.map(header => getComputedStyle(header).backgroundColor))
  expect(colors.at(-1)).toBe(colors.at(-2))
  expect(await table.locator('th').last().evaluate(el => getComputedStyle(el).position)).toBe('sticky')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await menu(page, 'Edit locker')
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  expect(state.writes).toHaveLength(0)
})
